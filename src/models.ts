/** Scale a normalized silhouette to a centered bounding box. Unknown keys return a rectangle. */
export function getModelOutline(id: string, width: number, height: number): ModelPoint[] {
  const points = MODEL_CATALOG[id]?.outline ?? [[-1,-1], [1,-1], [1,1], [-1,1]];
  return points.map(([x,y]) => [x * width / 2, y * height / 2]);
}

